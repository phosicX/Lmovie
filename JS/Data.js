const mediaDataManager = {
    databases: {
        movie: movieDatabase,
        tvDrama: tvDramaDatabase,
        animat: animatDatabase
    },
    
    pageConfig: {
        initial: 12,    // 初始加载数量
        more: 8         // 每次加载更多数量
    },
    
    currentState: {
        movie: {
            loadedItems: 0,
            allItems: Object.keys(movieDatabase).length,
            lastItemId: null
        },
        tvDrama: {
            loadedItems: 0,
            allItems: Object.keys(tvDramaDatabase).length,
            lastItemId: null
        },
        animat: {
            loadedItems: 0,
            allItems: Object.keys(animatDatabase).length,
            lastItemId: null
        }
    },
    
    initPage(pageType) {
        const state = this.currentState[pageType];
        const database = this.databases[pageType];
        const itemIds = Object.keys(database);
        
        state.allItems = itemIds.length;
        state.loadedItems = 0;
        state.lastItemId = null;
        
        return this.loadMoreItems(pageType, 'initial');
    },
    
    loadMoreItems(pageType, loadType = 'more') {
        const state = this.currentState[pageType];
        const database = this.databases[pageType];
        const itemIds = Object.keys(database);
        
        const loadCount = loadType === 'initial' 
            ? this.pageConfig.initial 
            : this.pageConfig.more;
        
        if (state.loadedItems >= state.allItems) {
            return [];
        }
        
        const startIndex = state.loadedItems;
        const endIndex = Math.min(startIndex + loadCount, state.allItems);
        
        const itemIdsToLoad = itemIds.slice(startIndex, endIndex);
        
        state.loadedItems = endIndex;
        state.lastItemId = itemIdsToLoad[itemIdsToLoad.length - 1] || null;
        
        return itemIdsToLoad.map(id => database[id]);
    },
    
    hasMoreItems(pageType) {
        const state = this.currentState[pageType];
        return state.loadedItems < state.allItems;
    },

    resetPage(pageType) {
        this.currentState[pageType].loadedItems = 0;
        this.currentState[pageType].lastItemId = null;
    },
    
    getLoadingStatus(pageType) {
        const state = this.currentState[pageType];
        return {
            loaded: state.loadedItems,
            total: state.allItems,
            hasMore: this.hasMoreItems(pageType)
        };
    }
};